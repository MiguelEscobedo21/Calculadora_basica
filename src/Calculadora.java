/**
 * Calculadora basica para
 * operaciones con dos numeros enteros
 */

public class Calculadora {

    /**
     * Suma de dos numeros
     * @param num1
     * @param num2
     * @return
     */
    public int suma(int num1, int num2){
        return num1 + num2;
    }

    /**
     * Resta dos numeros enteros
     * @param num1
     * @param num2
     * @return
     */
    public int resta(int num1, int num2){
        return num1 - num2;
    }

    /**
     * Multiplicacion de dos numeros
     * @param num1
     * @param num2
     * @return
     */
    public int multiplicacion(int num1, int num2){
        return num1 * num2;
    }

    /**
     * Division de dos numeros enteros
     * @param num1
     * @param num2
     * @return
     */
    public int division(int num1, int num2){
        return num1 / num2;
    }
}
